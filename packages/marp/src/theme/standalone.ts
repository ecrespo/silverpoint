/**
 * `@silverpoint/marp/theme.css` (DD-056, REQ-582): the theme for Marp CLI (`--theme`) and the Marp
 * VS Code extension (`markdown.marp.themes`), written by `tools/deck-theme` and diffed by its
 * `check`. Those hosts write no `data-sp-*` attribute, so the bare `section` is the first ground on
 * its first substrate and a ground's name as a class selects it; the attribute blocks follow, for
 * decks the silverpoint engine renders (REQ-583).
 */
import type { Ground } from '@silverpoint/core';
import { invertTokens, slideTokens, THEME_NAME, themeRules, tokenBlocks } from './silverpoint.css';

const block = (selector: string, tokens: Readonly<Record<string, string>>): string =>
  `${selector} {\n${Object.entries(tokens).map(([p, v]) => `  ${p}: ${v};`).join('\n')}\n}\n`;

const NOTE = `/*
 * Generated by tools/deck-theme from the ground objects (DD-056). Do not edit.
 *
 * In Marp CLI and the Marp VS Code extension this theme sets the type, the rules and the
 * colours of the built-in grounds (\`class: cyanotype\` selects the second one), but:
 * there are no generated backdrops (\`plate\` and \`hatched\` only inset the content),
 * \`silverpoint\` fences are shown as code, and there is no deck controller.
 * \`--engine @silverpoint/marp/cli\` renders the backdrops and the fences as static SVG (REQ-583).
 */
`;

export function standaloneTheme(grounds: readonly Ground[]): string {
  const [first, ...others] = grounds;
  if (!first) throw new Error('standaloneTheme needs at least one ground.');
  const firstOf = (ground: Ground): string => Object.values(ground.substrates)[0]!;
  return [
    `/* @theme ${THEME_NAME} */\n/* @size 16:9 1280px 720px */\n/* @size 4:3 960px 720px */\n`,
    NOTE,
    themeRules({ width: 1280, height: 720 }),
    block('section', slideTokens(first, firstOf(first))),
    block('section.invert', invertTokens(first, firstOf(first))),
    ...others.flatMap((g) => [block(`section.${g.name}`, slideTokens(g, firstOf(g))), block(`section.${g.name}.invert`, invertTokens(g, firstOf(g)))]),
    tokenBlocks(grounds),
  ].join('\n');
}
