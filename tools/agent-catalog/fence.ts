/**
 * `packages/marp/src/fence/charts.generated.ts` (T-258, REQ-591): each chart's declared props, by
 * slug, and the common chart props — what a `silverpoint` fence may put in `props`. The recipes
 * carry no prop metadata at run time, so the deck reads the catalog's, generated here and diffed
 * by `check`, as the server's assets are.
 */
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { AgentCatalog } from '../../packages/mcp/src/types';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
export const FENCE_FILE = join(ROOT, 'packages/marp/src/fence/charts.generated.ts');

export function fenceSource(catalog: Pick<AgentCatalog, 'charts' | 'common'>): string {
  const rows = [...catalog.charts]
    .sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0))
    .map((c) => `  '${c.slug}': [${c.props.map((p) => `'${p.name}'`).join(', ')}],`);
  return [
    '// Generated by `pnpm --filter @silverpoint/agent-catalog generate` (tools/agent-catalog/fence.ts). Do not edit.',
    '',
    '/** Each chart’s own props, by catalog slug. */',
    'export const CHART_PROPS: Readonly<Record<string, readonly string[]>> = {',
    ...rows,
    '};',
    '',
    '/** The props every chart takes. */',
    `export const COMMON_PROPS: readonly string[] = [${catalog.common.chart.map((p) => `'${p.name}'`).join(', ')}];`,
    '',
  ].join('\n');
}
