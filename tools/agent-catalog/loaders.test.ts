import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, test } from 'vitest';
import { LOADER_FILES, loaderSource } from './loaders';

/* Each adapter's deck/chart-loaders.ts (T-272, REQ-593, DD-053): slug → lazy chart module. */

const ROOT = join(__dirname, '../..');
const catalog = JSON.parse(readFileSync(join(ROOT, 'packages/mcp/agent-catalog.json'), 'utf8'));
const slugs: string[] = catalog.charts.map((c: { slug: string }) => c.slug).sort();
const rows = (source: string) => [...source.matchAll(/^ {2}'([a-z-]+)': \(\) => import\('([^']+)'\)\.then\(\(m\) => m\.(\w+)\),$/gm)].map((m) => ({ slug: m[1]!, from: m[2]!, name: m[3]! }));

describe('chart loaders (T-272)', () => {
  test.each(['react', 'vue', 'angular'] as const)('REQ-593 · %s: one lazy loader per catalog slug, in slug order', (adapter) => {
    const source = loaderSource(catalog, adapter);
    expect(source.startsWith('// Generated by `pnpm --filter @silverpoint/agent-catalog generate`')).toBe(true);
    expect(rows(source).map((r) => r.slug)).toEqual(slugs);
  });

  test('REQ-593 · React and Vue import the chart’s own source entry, relative to deck/; with the adapter’s export name', () => {
    for (const adapter of ['react', 'vue'] as const) {
      const pkg = JSON.parse(readFileSync(join(ROOT, `packages/${adapter}/package.json`), 'utf8'));
      for (const row of rows(loaderSource(catalog, adapter))) {
        const entry = pkg.exports[`./${row.slug}`]['@silverpoint/source'] as string;
        expect(row.from).toBe(entry.replace(/^\.\/src\//, '../').replace(/\.tsx?$/, ''));
        expect(existsSync(join(ROOT, `packages/${adapter}/src/deck`, `${row.from}${adapter === 'react' && !row.from.endsWith('-entry') ? '.tsx' : '.ts'}`)), row.from).toBe(true);
        expect(row.name).toBe(catalog.charts.find((c: { slug: string }) => c.slug === row.slug).names[adapter]);
      }
    }
    expect(rows(loaderSource(catalog, 'react')).find((r) => r.slug === 'line-chart')!.from).toBe('../line-chart-entry');
  });

  test('REQ-593 · Angular imports each secondary entry point by package name, and its public API exports the class', () => {
    for (const row of rows(loaderSource(catalog, 'angular'))) {
      expect(row.from).toBe(`@silverpoint/angular/${row.slug}`);
      expect(readFileSync(join(ROOT, `packages/angular/${row.slug}/public-api.ts`), 'utf8')).toMatch(new RegExp(`export \\{[^}]*\\b${row.name}\\b`));
    }
  });

  test('REQ-593 · the files are current (check diffs them)', () => {
    for (const adapter of ['react', 'vue', 'angular'] as const) expect(readFileSync(LOADER_FILES[adapter], 'utf8')).toBe(loaderSource(catalog, adapter));
  });
});
