/**
 * `@silverpoint/embed`'s generated sources (feature-007, T-293, DD-061, DD-062): the prop tables
 * from the same source as the deck fence's, the registry of the 60 recipes imported by name (so a
 * bundle keeps the recipes and nothing else of the core), the stylesheet text and version, and the
 * three EB Garamond cuts. Written by `generate`, diffed by `check`.
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { AgentCatalog } from '../../packages/mcp/src/types';
import { minifyCss } from './assets';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const SRC = join(ROOT, 'packages/embed/src');
export const EMBED_PROPS_FILE = join(SRC, 'spec/charts.generated.ts');
export const EMBED_RECIPES_FILE = join(SRC, 'recipes.generated.ts');
export const EMBED_ASSETS_FILE = join(SRC, 'render/assets.generated.ts');
export const EMBED_FONTS_FILE = join(SRC, 'render/fonts.generated.ts');
const HEADER = '// Generated by `pnpm --filter @silverpoint/agent-catalog generate` (tools/agent-catalog/embed.ts). Do not edit.';

/** `bar-chart` → `barChart`, the recipe's export name. */
export const camel = (slug: string): string => slug.replace(/-([a-z0-9])/g, (_m, c: string) => c.toUpperCase());

export function embedPropsSource(catalog: Pick<AgentCatalog, 'charts' | 'common'>): string {
  return [
    HEADER,
    '',
    '/** Each chart’s own props, by catalog slug, in the catalog’s order (REQ-631). */',
    'export const CHART_PROPS: Readonly<Record<string, readonly string[]>> = {',
    ...catalog.charts.map((c) => `  '${c.slug}': [${c.props.map((p) => `'${p.name}'`).join(', ')}],`),
    '};',
    '',
    '/** The props every chart takes. */',
    `export const COMMON_PROPS: readonly string[] = [${catalog.common.chart.map((p) => `'${p.name}'`).join(', ')}];`,
    '',
  ].join('\n');
}

/** Which charts the core's main entry exports; the rest are on `@silverpoint/core/catalog`. */
function coreExports(): Set<string> {
  const index = readFileSync(join(ROOT, 'packages/core/src/index.ts'), 'utf8');
  return new Set([...index.matchAll(/\b([a-z][A-Za-z0-9]*)\b/g)].map((m) => m[1]!));
}

export function embedRecipesSource(catalog: Pick<AgentCatalog, 'charts'>): string {
  const main = coreExports();
  const fromCore = catalog.charts.filter((c) => main.has(camel(c.slug)));
  const fromCatalog = catalog.charts.filter((c) => !main.has(camel(c.slug)));
  return [
    HEADER,
    '',
    "import type { ChartRecipe, CommonChartProps } from '@silverpoint/core';",
    `import { ${fromCore.map((c) => camel(c.slug)).join(', ')} } from '@silverpoint/core';`,
    `import { ${fromCatalog.map((c) => camel(c.slug)).join(', ')} } from '@silverpoint/core/catalog';`,
    '',
    '/** The 60 recipes by catalog slug, in the agent catalog’s order (I-55). */',
    'export const RECIPES: ReadonlyMap<string, ChartRecipe<CommonChartProps>> = new Map<string, ChartRecipe<CommonChartProps>>([',
    ...catalog.charts.map((c) => `  ['${c.slug}', ${camel(c.slug)} as unknown as ChartRecipe<CommonChartProps>],`),
    ']);',
    '',
  ].join('\n');
}

export function embedAssetsSource(): string {
  const version = (JSON.parse(readFileSync(join(ROOT, 'packages/core/package.json'), 'utf8')) as { version: string }).version;
  return [
    HEADER,
    '',
    '/** The library version this package is (REQ-651). */',
    `export const VERSION = ${JSON.stringify(version)};`,
    '',
    '/** `@silverpoint/grounds` styles.css, minified: the same text `render_chart` inlines (DD-047, REQ-660). */',
    `export const GROUND_CSS = ${JSON.stringify(minifyCss(readFileSync(join(ROOT, 'packages/grounds/src/styles.css'), 'utf8')))};`,
    '',
  ].join('\n');
}

const FACES = [
  ['EB_GARAMOND_400', 'eb-garamond-latin-400-normal.woff2'],
  ['EB_GARAMOND_500', 'eb-garamond-latin-500-normal.woff2'],
  ['EB_GARAMOND_400_ITALIC', 'eb-garamond-latin-400-italic.woff2'],
] as const;

export function embedFontsSource(): string {
  return [
    HEADER,
    '',
    '/** EB Garamond, latin subset, WOFF2 in base64 (`@silverpoint/fonts`, OFL-1.1). Only the `full` file and `embedFonts` carry them (DD-062). */',
    ...FACES.map(([name, file]) => `export const ${name} = ${JSON.stringify(readFileSync(join(ROOT, 'packages/fonts/files', file)).toString('base64'))};`),
    '',
  ].join('\n');
}

/** Every generated file of the package, path → content. */
export function embedFiles(catalog: Pick<AgentCatalog, 'charts' | 'common'>): Map<string, string> {
  return new Map([
    [EMBED_PROPS_FILE, embedPropsSource(catalog)],
    [EMBED_RECIPES_FILE, embedRecipesSource(catalog)],
    [EMBED_ASSETS_FILE, embedAssetsSource()],
    [EMBED_FONTS_FILE, embedFontsSource()],
  ]);
}
