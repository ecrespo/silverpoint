/**
 * Each adapter's `deck/chart-loaders.ts` (T-272, REQ-593, DD-053): the 60 catalog slugs, each to a
 * lazy import of its chart, so a two-chart deck does not bundle sixty. Generated from the catalog
 * and the adapters' package exports, and diffed by `check`.
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { AgentCatalog } from '../../packages/mcp/src/types';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');

export type LoaderAdapter = 'react' | 'vue' | 'angular';

export const LOADER_FILES: Readonly<Record<LoaderAdapter, string>> = {
  react: join(ROOT, 'packages/react/src/deck/chart-loaders.ts'),
  vue: join(ROOT, 'packages/vue/src/deck/chart-loaders.ts'),
  angular: join(ROOT, 'packages/angular/deck/chart-loaders.ts'),
};

const HEADER: Readonly<Record<LoaderAdapter, string[]>> = {
  react: ["import type { ComponentType } from 'react';", '', '// Each chart takes its own props: the loader only promises a component.', 'export type ChartLoader = () => Promise<ComponentType<any>>;'],
  vue: ["import type { Component } from 'vue';", '', 'export type ChartLoader = () => Promise<Component>;'],
  angular: ["import type { Type } from '@angular/core';", '', 'export type ChartLoader = () => Promise<Type<unknown>>;'],
};

/** Where an adapter's chart lives, as `deck/` imports it. */
function modulePath(adapter: LoaderAdapter, slug: string): string {
  // ng-packagr: a secondary entry point imports another by its package name, never by path.
  if (adapter === 'angular') return `@silverpoint/angular/${slug}`;
  const pkg = JSON.parse(readFileSync(join(ROOT, `packages/${adapter}/package.json`), 'utf8')) as { exports: Record<string, Record<string, string>> };
  const source = pkg.exports[`./${slug}`]?.['@silverpoint/source'];
  if (!source) throw new Error(`@silverpoint/${adapter} exports no ./${slug}`);
  return source.replace(/^\.\/src\//, '../').replace(/\.tsx?$/, '');
}

export function loaderSource(catalog: Pick<AgentCatalog, 'charts'>, adapter: LoaderAdapter): string {
  const charts = [...catalog.charts].sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));
  // Angular's chart classes carry the same names as Vue's components (`SpBarChart`).
  const nameOf = (c: (typeof charts)[number]) => (adapter === 'angular' ? c.names.vue : c.names[adapter]);
  return [
    '// Generated by `pnpm --filter @silverpoint/agent-catalog generate` (tools/agent-catalog/loaders.ts). Do not edit.',
    ...HEADER[adapter],
    '',
    '/** Each fence chart, by catalog slug, loaded when a deck first hydrates it (DD-053). */',
    'export const CHART_LOADERS: Readonly<Record<string, ChartLoader>> = {',
    ...charts.map((c) => `  '${c.slug}': () => import('${modulePath(adapter, c.slug)}').then((m) => m.${nameOf(c)}),`),
    '};',
    '',
  ].join('\n');
}
