/** References written from a template of the same name, beside the chart families. */
const TEMPLATED = ['choosing-charts', 'components', 'overlays', 'grounds-and-palettes', 'dashboard', 'timeline', 'react', 'vue', 'angular', 'reflex', 'pitfalls'];

const GENERATED = 'Generated by tools/agent-catalog from skills/silverpoint/templates and the agent catalog. Do not edit: run `pnpm --filter @silverpoint/agent-catalog generate`.';

// ── Markdown pieces ─────────────────────────────────────────────────────────────────────────────

const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const code = (text: string): string => `\`${cell(text)}\``;
const list = (items: readonly string[]): string => items.map(code).join(', ');

function table(head: readonly string[], rows: readonly (readonly string[])[]): string {
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

/** A line of links to the sections that follow, for a reference read in parts. */
const contents = (titles: readonly string[]): string => `**Contents:** ${titles.map((t) => `[${t}](#${t.toLowerCase()})`).join(' · ')}`;

function propsTable(props: readonly PropEntry[]): string {
  if (props.length === 0) return '*No props of its own.*';
  return table(
    ['Prop', 'Type', 'Default', 'Notes'],
    props.map((p) => [code(p.name), code(p.type), p.default ? code(p.default) : '', `${p.optional ? '' : '**Required.** '}${cell(p.doc)}`.trim()]),
  );
}

function namesTable(entry: { readonly names: ChartEntry['names']; readonly imports: ChartEntry['imports'] }): string {
  const frameworks = ['react', 'vue', 'angular', 'reflex'] as const;
  return table(
    ['', 'React', 'Vue', 'Angular', 'Reflex'],
    [
      ['Name', ...frameworks.map((f) => code(entry.names[f]))],
      ['Import', ...frameworks.map((f) => code(entry.imports[f]))],
    ],
  );
}

const FENCE: Readonly<Record<string, string>> = { react: 'tsx', vue: 'vue', angular: 'ts angular', reflex: 'python' };

function examples(catalog: Catalog, input: Omit<GenerateInput, 'framework'>, frameworks: readonly string[]): string {
  return frameworks.map((framework) => `\`\`\`${FENCE[framework]}\n${generateCode(catalog, { ...input, framework }).code.trimEnd()}\n\`\`\``).join('\n\n');
}

/**
 * The demo's own field names, so a chart's example reads the sample rows printed beside it; a
 * required field the demo reads through its default is named too, so every example shows which
 * prop names which field.
 */
function demoFields(chart: ChartEntry): Record<string, string | readonly string[]> {
  const keys = chart.demoKeys ?? {};
  return Object.fromEntries(
    chart.data.fields.flatMap((f) => {
      const name = keys[f.prop];
      if (typeof name === 'string' || (Array.isArray(name) && name.every((n) => typeof n === 'string'))) return [[f.role, name as string | readonly string[]]];
      const fallback = f.required ? chart.props.find((p) => p.name === f.prop)?.default?.match(/^'([^']+)'$/)?.[1] : undefined;
      return fallback ? [[f.role, fallback]] : [];
    }),
  );
}

// ── Blocks ──────────────────────────────────────────────────────────────────────────────────────

function chartSection(catalog: Catalog, chart: ChartEntry): string {
  const data = catalog.data;
  const parts = [
    `## ${chart.names.react}`,
    '',
    `${code(chart.slug)} · ${chart.summary}`,
    '',
    namesTable(chart),
    '',
    `**Data:** shape ${code(chart.data.shape)}; intents ${list(chart.intents)}.`,
  ];
  if (chart.data.fields.length > 0) {
    parts.push('', table(['Role', 'Accessor prop', 'Type', 'Required'], chart.data.fields.map((f) => [f.role, code(f.prop), f.type, f.required ? 'yes' : 'no'])));
  } else {
    parts.push('', 'It draws from its props alone; `data` is not read.');
  }
  if (chart.demoSample && chart.demoSample.length > 0) {
    const keys = chart.demoKeys && Object.keys(chart.demoKeys).length > 0 ? ` (read through ${Object.entries(chart.demoKeys).map(([k, v]) => `${k}=${JSON.stringify(v)}`).join(', ')})` : '';
    parts.push('', `The demo's first rows${keys}, drawn when \`data\` is omitted:`, '', '```json', JSON.stringify(chart.demoSample, null, 1).replace(/\n\s*/g, ' '), '```');
  }
  if (chart.drillable) parts.push('', 'Drillable: bind `rootId` and listen to `onRootChange` (`@root-change`, `(rootChange)`); the chart holds no root of its own.');
  parts.push('', '### Props', '', `Its own props; the ${data.common.chart.length} common ones are in [choosing-charts.md](../choosing-charts.md#common-chart-props).`, '', propsTable(chart.props));
  parts.push('', '### Example', '', examples(catalog, { target: { chart: chart.slug }, fields: demoFields(chart) }, ['react', 'vue', 'angular']));
  return parts.join('\n');
}

function componentSection(catalog: Catalog, component: ComponentEntry): string {
  const parts = [`## ${component.names.react}`, '', `${code(component.slug)} · ${component.summary} (${component.group})`, '', namesTable(component)];
  const binding = component.binding;
  for (const kind of ['value', 'open'] as const) {
    const bound = binding?.[kind];
    if (bound) parts.push('', `**${kind === 'value' ? 'Value' : 'Open state'}:** React ${code(bound.react)}, Vue ${code(bound.vue)}, Angular ${code(bound.angular)}.`);
  }
  const events = component.events;
  if (events.react.length > 0) parts.push('', `**Events:** React ${list(events.react)}; Vue ${list(events.vue)}; Angular ${list(events.angular)}.`);
  const slots = component.slots;
  if (slots.react.length + slots.vue.length + slots.angular.length > 0) {
    parts.push('', `**Content:** React ${list(slots.react) || '—'}; Vue ${list(slots.vue) || '—'}; Angular ${list(slots.angular) || '—'}.`);
  }
  if (component.states.length > 0) parts.push('', `**States:** ${list(component.states)}.`);
  parts.push('', '### Props', '', `Its own props, beside the common ones (${list(catalog.data.common.ui.map((p) => p.name))}).`, '', propsTable(component.props));
  parts.push('', '### Example', '', examples(catalog, { target: { component: component.slug } }, ['react', 'vue', 'angular']));
  return parts.join('\n');
}

function blocks(catalog: Catalog): Readonly<Record<string, () => string>> {
  const data = catalog.data;
  const family = (slug: string) => data.charts.filter((c) => c.family === slug);
  return {
    'chart-index': () =>
      data.families
        .map((f) => `- **${f.title}** — [references/charts/${f.slug}.md](references/charts/${f.slug}.md): ${list(family(f.slug).map((c) => c.slug))}`)
        .join('\n'),
    'component-index': () =>
      [
        ['ui', 'UI components', 'references/components.md'],
        ['composed', 'Composed components', 'references/components.md'],
        ['overlay', 'Overlays', 'references/overlays.md'],
      ]
        .map(([kind, title, file]) => `- **${title}** — [${file}](${file}): ${list(data.components.filter((c) => c.family === kind).map((c) => c.slug))}`)
        .join('\n'),
    'chart-table': () =>
      table(
        ['Chart', 'Family', 'Shape', 'Intents', 'Summary'],
        data.charts.map((c) => [code(c.slug), c.family, code(c.data.shape), c.intents.join(', '), cell(c.summary)]),
      ),
    'recommend-table': () =>
      table(
        ['Shape', 'Intent', 'Charts, best first', 'Adjustments'],
        data.recommend.map((r) => [
          code(r.shape),
          code(r.intent),
          r.charts.map((c) => `${code(c.slug)} ${c.score} — ${cell(c.reason)}`).join('<br>'),
          (r.adjust ?? []).map((a) => `${a.when}${a.n}: ${code(a.slug)} ${a.delta > 0 ? '+' : ''}${a.delta} — ${cell(a.reason)}`).join('<br>'),
        ]),
      ),
    'common-chart-props': () => propsTable(data.common.chart),
    components: () => {
      const listed = data.components.filter((c) => c.family !== 'overlay');
      return [contents(listed.map((c) => c.names.react)), '', listed.map((c) => componentSection(catalog, c)).join('\n\n')].join('\n');
    },
    overlays: () => {
      const listed = data.components.filter((c) => c.family === 'overlay');
      return [contents(listed.map((c) => c.names.react)), '', listed.map((c) => componentSection(catalog, c)).join('\n\n')].join('\n');
    },
    grounds: () => table(['Ground', 'Substrates', 'What it draws'], data.grounds.map((g) => [code(g.name), list(g.substrates), cell(g.summary)])),
    'palette-fields': () => propsTable(data.palettes.fields),
    'palette-presets': () => {
      const fields = data.palettes.fields.map((f) => f.name);
      return table(
        ['Preset', ...fields.map(code)],
        Object.entries(data.palettes.presets).map(([name, palette]) => [code(name), ...fields.map((f) => (palette[f] ? palette[f] : ''))]),
      );
    },
    'dashboard-props': () => [namesTable(data.dashboard), '', '### Dashboard props', '', propsTable(data.dashboard.props)].join('\n'),
    'dashboard-layout': () => [propsTable(data.dashboard.layout), '', '### Cell layout (`layout.cells[]`)', '', propsTable(data.dashboard.cell)].join('\n'),
    timeline: () => [namesTable(data.timeline), '', `Optional peer: ${code(data.timeline.peer)}.`, '', propsTable(data.timeline.props)].join('\n'),
    stylesheets: () =>
      table(
        ['When', 'Stylesheets, in this order'],
        [
          ['Always', list(data.stylesheets.always)],
          ['With UI components, composed components or overlays', list(data.stylesheets.ui)],
          ['With the timeline', list(data.stylesheets.timeline)],
        ],
      ),
    diagnostics: () => table(['Code', 'Severity', 'Requirement', 'What it means', 'What to do'], data.diagnostics.map((d) => [code(d.code), d.severity, d.req, cell(d.what), cell(d.todo)])),
    'reflex-names': () =>
      table(
        ['Slug', 'Builder', 'Kind'],
        [...data.charts.map((c) => [code(c.slug), code(c.names.reflex), 'chart']), ...data.components.map((c) => [code(c.slug), code(c.names.reflex), c.family])],
      ),
    'reflex-examples': () =>
      [examples(catalog, { target: { chart: 'line-chart' }, fields: demoFields(catalog.chart('line-chart')) }, ['reflex']), examples(catalog, { target: { component: 'modal' } }, ['reflex'])].join('\n\n'),
    'react-example': () => examples(catalog, { target: { chart: 'line-chart' }, fields: demoFields(catalog.chart('line-chart')), palette: 'sanguine' }, ['react']),
    'vue-example': () => examples(catalog, { target: { component: 'select' } }, ['vue']),
    'angular-example': () => examples(catalog, { target: { component: 'modal' } }, ['angular']),
  };
}

// ── Assembly ────────────────────────────────────────────────────────────────────────────────────

function render(template: string, catalog: Catalog, source: string): string {
  const table = blocks(catalog);
  return template
    .replace(/\{\{version\}\}/g, catalog.version)
    .replace(/\{\{reflexVersion\}\}/g, catalog.data.reflex.version)
    .replace(/<!-- generated:([a-z-]+) -->/g, (_, name: string) => {
      const block = table[name];
      if (!block) throw new Error(`${source}: no generated block named ${name}`);
      return block();
    });
}

/** The version line every reference carries under its title (REQ-554). */
function stamped(markdown: string, version: string): string {
  const [title, ...rest] = markdown.split('\n');
  return [`<!-- ${GENERATED} -->`, title, '', `*Describes silverpoint ${version}.*`, ...rest].join('\n');
}

/** Every file of the skill, by path under `skills/silverpoint/`, templates aside. */
export function skillFiles(data: AgentCatalog): Map<string, string> {
  const catalog = new Catalog(data);
  const template = (name: string) => readFileSync(join(TEMPLATES, name), 'utf8');
  const files = new Map<string, string>();

  const skill = render(template('SKILL.md'), catalog, 'SKILL.md');
  const end = skill.indexOf('\n---\n', 4) + 5;
  files.set('SKILL.md', `${skill.slice(0, end)}\n<!-- ${GENERATED} -->\n${skill.slice(end)}`);

  for (const name of TEMPLATED) files.set(`references/${name}.md`, stamped(render(template(`${name}.md`), catalog, `${name}.md`), catalog.version));
  files.set(
    'references/diagnostics.md',
    stamped(['# Diagnostics', '', 'Every `SP` code the library warns or throws, in development builds.', '', blocks(catalog).diagnostics!(), ''].join('\n'), catalog.version),
  );
  for (const family of data.families) {
    const charts = data.charts.filter((c) => c.family === family.slug);
    const body = [
      `# ${family.title}`,
      '',
      `${charts.length} charts. Shared props, the data shapes and the recommender are in [choosing-charts.md](../choosing-charts.md).`,
      '',
      contents(charts.map((c) => c.names.react)),
      '',
      charts.map((c) => chartSection(catalog, c)).join('\n\n'),
      '',
    ].join('\n');
    files.set(`references/charts/${family.slug}.md`, stamped(body, catalog.version));
  }
  return files;
}

/** `packages/mcp/src/guides.generated.ts`: the guides the server serves, read from no file at run time. */
export function guidesSource(files: ReadonlyMap<string, string>): string {
  const entries = Object.entries(GUIDE_FILES).map(([topic, path]) => `  ${JSON.stringify(topic)}: ${JSON.stringify(files.get(path) ?? '')},`);
  return [
    '// Generated by tools/agent-catalog (pnpm --filter @silverpoint/agent-catalog generate). Do not edit.',
    '',
    '/** The `silverpoint` skill’s references, served as `silverpoint://guides/{topic}` (API delta §4). */',
    'export const GUIDES: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

