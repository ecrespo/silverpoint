/**
 * The `silverpoint` skill (API delta §6, DD-050, REQ-552, REQ-554): the hand-written templates in
 * `skills/silverpoint/templates/` with the agent catalog's tables written into them, and one
 * reference per chart family generated whole. `generate` writes it, `check` diffs it, and the
 * server serves its guides from `packages/mcp/src/guides.generated.ts` (API delta §4).
 *
 * A template is Markdown with `{{version}}`, `{{reflexVersion}}` and `<!-- generated:<block> -->`
 * markers; an unknown marker fails the build.
 */
