/** `plugin.json` at the catalog's version; every other field is hand-written and kept. */
export function pluginManifest(source: string, version: string): string {
  return `${JSON.stringify({ ...(JSON.parse(source) as object), version }, null, 2)}\n`;
}

/** `marketplace.json` with its plugin at the catalog's version. */
export function marketplaceManifest(source: string, version: string): string {
  const marketplace = JSON.parse(source) as { plugins: { name: string; version?: string }[] };
  marketplace.plugins = marketplace.plugins.map((p) => (p.name === 'silverpoint' ? { ...p, version } : p));
  return `${JSON.stringify(marketplace, null, 2)}\n`;
}

// ── Example extraction (REQ-557) ────────────────────────────────────────────────────────────────

export interface Example {
  /** The file it came from and its place there: `references-charts-flows-3`. */
  readonly name: string;
  readonly framework: 'react' | 'vue' | 'angular' | 'reflex';
  readonly ext: 'tsx' | 'vue' | 'ts' | 'py';
  readonly code: string;
}

/** Fences that hold no code to compile. */
const PROSE = new Set(['sh', 'css', 'json', 'text']);

/**
 * Every code fence of the skill as a file to compile: `tsx` (React), `vue` (a Vue SFC),
 * `ts <react|vue|angular>` (a module of that app) and `python` (Reflex). A fence in any other
 * language, or with none, is refused: every example compiles or says it is not code.
 */
export function extractExamples(files: ReadonlyMap<string, string>): Example[] {
  const found: Example[] = [];
  for (const [path, markdown] of files) {
    const base = path.replace(/\.md$/, '').replace(/[^a-zA-Z0-9]+/g, '-');
    let index = 0;
    for (const match of markdown.matchAll(/^```([^\n]*)\n([\s\S]*?)^```$/gm)) {
      const info = match[1]!.trim();
      const body = match[2]!;
      const [lang = '', framework] = info.split(/\s+/);
      if (!lang) throw new Error(`${path}: a code fence without a language`);
      if (PROSE.has(lang)) continue;
      const kind = (() => {
        if (lang === 'tsx' && !framework) return { framework: 'react', ext: 'tsx' } as const;
        if (lang === 'vue' && !framework) return { framework: 'vue', ext: 'vue' } as const;
        if (lang === 'python' && !framework) return { framework: 'reflex', ext: 'py' } as const;
        if (lang === 'ts' && (framework === 'react' || framework === 'vue' || framework === 'angular')) return { framework, ext: 'ts' } as const;
        return undefined;
      })();
      if (!kind) throw new Error(`${path}: \`\`\`${info} is not a fence the examples check compiles (tsx, vue, ts react|vue|angular, python; sh, css, json, text)`);
      index += 1;
      found.push({ name: `${base}-${index}`, ...kind, code: body });
    }
  }
  return found;
}
