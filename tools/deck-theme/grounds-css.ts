/**
 * `packages/marp/src/cli/grounds-css.generated.ts` (T-266, REQ-583): the grounds' chart stylesheet,
 * minified, for the Marp CLI engine to add to a deck's CSS — Marp CLI loads one theme, and a fence's
 * chart is painted by `@silverpoint/grounds/styles.css`. Written by `generate`, diffed by `check`.
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { minifyCss } from '../agent-catalog/assets';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
export const GROUNDS_CSS_FILE = join(ROOT, 'packages/marp/src/cli/grounds-css.generated.ts');

export function groundsCssSource(): string {
  const css = minifyCss(readFileSync(join(ROOT, 'packages/grounds/src/styles.css'), 'utf8'));
  return `// Generated by \`pnpm --filter @silverpoint/deck-theme generate\` (tools/deck-theme/grounds-css.ts). Do not edit.\n\n/** \`@silverpoint/grounds/styles.css\`, minified. */\nexport const GROUNDS_CSS = ${JSON.stringify(css)};\n`;
}
